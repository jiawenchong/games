/* ---------- 建構畫面 ---------- */
(function buildLessons() {
  const root = document.getElementById('lessons');
  if (!root) return;

  LESSONS.forEach((L, idx) => {
    const card = document.createElement('details');
    card.className = 'lesson';
    if (idx === 0) card.open = true;

    const sum = document.createElement('summary');
    sum.innerHTML = `<span class="lesson-icon">${L.icon}</span><span class="lesson-title">${L.title}</span>`;
    card.appendChild(sum);

    const body = document.createElement('div');
    body.className = 'lesson-body';
    body.innerHTML =
      `<p class="lesson-lead">${L.lead}</p>` +
      L.body.map(p => `<p>${p}</p>`).join('') +
      `<ul class="lesson-points">${L.points.map(p => `<li>${p}</li>`).join('')}</ul>` +
      `<div class="lesson-try"><button type="button" class="try-btn">🧪 ${L.tryLabel}</button>` +
      `<p class="lesson-watch"><b>看點:</b>${L.watch}</p></div>`;
    card.appendChild(body);

    body.querySelector('.try-btn').addEventListener('click', () => {
      if (typeof applyLessonSetup === 'function') applyLessonSetup(L.cfg);
      document.getElementById('canvas-wrap').scrollIntoView({ behavior: 'smooth', block: 'center' });
    });

    root.appendChild(card);
  });

  const gl = document.getElementById('glossary-list');
  if (gl) {
    gl.innerHTML = GLOSSARY
      .map(([term, def]) => `<div class="term"><b>${term}</b><span>${def}</span></div>`)
      .join('');
  }
})();
